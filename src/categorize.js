/**
 * 가맹점 이름 정규화 (대소문자·공백·기호 제거 → OCR 변형에 덜 민감: "GS25 역삼점" = "gs25역삼점")
 * 학습한 분류를 찾을 때와, 같은 거래인지 비교할 때 씁니다.
 */
export function normMerchant(s) {
  return String(s || "").toLowerCase().replace(/[^0-9a-z가-힣]/g, "");
}

/**
 * 가맹점명 → 카테고리 (못 맞추면 '기타')
 */
export function categorize(merchant) {
  if (!merchant) return "기타";
  const name = String(merchant).toLowerCase();
  let best = "기타";
  let bestLen = 0;
  for (const [category, keywords] of RULES) {
    for (const kw of keywords) {
      if (kw.length > bestLen && hasKeyword(name, kw)) {
        best = category;
        bestLen = kw.length;
      }
    }
  }
  return best;
}

// 짧은 영문 약어(cu·kt·kfc·cgv 등)는 앞뒤가 영문·숫자가 아닐 때만 — "Curry"의 cu나 "skt"의 kt처럼
// 다른 단어 안에 든 건 아님 ("CU성수점"처럼 한글이 바로 붙은 건 인정)
function hasKeyword(name, kw) {
  if (!/^[a-z0-9]{1,3}$/.test(kw)) return name.includes(kw);
  for (let i = name.indexOf(kw); i >= 0; i = name.indexOf(kw, i + 1)) {
    if (!/[a-z0-9]/.test(name[i - 1] || "") && !/[a-z0-9]/.test(name[i + kw.length] || "")) return true;
  }
  return false;
}
